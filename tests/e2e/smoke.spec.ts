import { expect, test } from '@playwright/test';

test('starts a playable farm', async ({ page }) => {
  await page.goto('/');
  await expect(page.getByRole('heading', { name: /NUSANTARA FARM/i })).toBeVisible();
  await page.getByRole('button', { name: 'Mulai Petualangan' }).click();
  await expect(page.getByText('MISI HARI INI')).toBeVisible({ timeout: 20_000 });
  await expect(page.getByLabel('Area permainan kebun')).toBeVisible();
  await expect(page.locator('.game-shell canvas')).toBeVisible({ timeout: 20_000 });
  await expect(page.getByRole('button', { name: 'Ekspor' })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Pulihkan' })).toBeVisible();
  await expect(page.getByText('Impor Save')).toBeVisible();
  await page.getByRole('button', { name: 'Simpan', exact: true }).click();
  await expect(page.getByText('Permainan tersimpan di perangkat ini.')).toBeVisible();
  await page.getByRole('button', { name: 'Simpan', exact: true }).click();
  await page.getByRole('button', { name: 'Pulihkan' }).click();
  await expect(page.getByText('Backup terakhir berhasil dipulihkan.')).toBeVisible();
  await page.getByRole('button', { name: /Kelola Peternakan/ }).click();
  await expect(page.getByRole('heading', { name: 'Rawat Ternak' })).toBeVisible();
  await expect(page.getByText(/Cici · Ayam/)).toBeVisible();
  await page.getByRole('button', { name: '×', exact: true }).click();
  await page.getByRole('button', { name: 'Kios Pak Jaya' }).click();
  await expect(page.getByRole('button', { name: /Benih Cabai/ })).toBeVisible();
  await page.getByRole('button', { name: '×', exact: true }).click();
  await page.getByRole('button', { name: 'Pergi Memancing' }).click();
  await expect(page.getByRole('heading', { name: 'Sungai' })).toBeVisible();
  await expect(page.getByText('ENSIKLOPEDIA IKAN')).toBeVisible();
  await page.getByRole('button', { name: '×', exact: true }).click();
  await page.getByRole('button', { name: 'Jelajahi Hutan' }).click();
  await expect(page.getByRole('heading', { name: 'Foraging' })).toBeVisible();
  await page.getByRole('button', { name: '×', exact: true }).click();
  await page.getByRole('button', { name: 'Bangun & Produksi' }).click();
  await expect(page.getByRole('heading', { name: 'Bangun & Tata Kebun' })).toBeVisible();
  await page.getByRole('button', { name: 'Memasak' }).click();
  await expect(page.getByRole('heading', { name: 'Dapur Nusantara' })).toBeVisible();
  await page.getByRole('button', { name: '×', exact: true }).click();
  await page.getByRole('button', { name: 'Peta & Eksplorasi' }).click();
  await expect(page.getByText('PETA NUSANTARA')).toBeVisible();
  await expect(page.getByText('Tambang', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '×', exact: true }).click();
  await page.getByRole('button', { name: 'Kebun Lanjutan' }).click();
  await expect(page.getByRole('heading', { name: 'Orchard, Lebah & Kolam' })).toBeVisible();
  await expect(page.getByText('PETERNAKAN LEBAH')).toBeVisible();
  await page.getByRole('button', { name: '×', exact: true }).click();
  await page.getByRole('button', { name: 'Desa & Kalender' }).click();
  await expect(page.getByRole('heading', { name: /Desa · Reputasi/ })).toBeVisible();
  await page.getByRole('button', { name: 'Quest' }).click();
  await expect(page.getByText('Panen Pertama')).toBeVisible();
  await page.getByRole('button', { name: '×', exact: true }).click();
  await page.getByRole('button', { name: 'Koleksi & Rumah' }).click();
  await expect(page.getByRole('heading', { name: 'Rumah dan Sahabat' })).toBeVisible();
  await expect(page.getByText('BUG CATCHING')).toBeVisible();
});
